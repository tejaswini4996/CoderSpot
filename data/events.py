# Give every event a stable numeric id (1, 2, 3, ...) based on its position
# in the list above. This id is what the "Apply" links and the applications
# database use to know which program someone applied to — you don't need to
# add it by hand when editing EVENTS.
for _index, _event in enumerate(EVENTS, start=1):
    _event["id"] = _index


def get_event_by_id(event_id):
    """Look up a single event by its id. Returns None if not found."""
    for event in EVENTS:
        if event["id"] == event_id:
            return event
    return None
